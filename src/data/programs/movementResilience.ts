function applyWeek(item: TemplateItem, weekIndex: number): TemplateItem {
  if (!item.weekly) return item;
  const next: TemplateItem = { ...item };
  for (const [key, values] of Object.entries(item.weekly)) {
    const value = (values as [number, number, number, number])[weekIndex];
    if (typeof value === 'number') {
      (next as unknown as Record<string, number>)[key] = value;
    }
  }
  return next;
}

export function buildWorkoutDay(template: DayTemplate, weekNumber: number): WorkoutDay {
  const weekIndex = weekNumber - 1;
  const prescriptions = template.items.map((raw) => {
    const item = applyWeek(raw, weekIndex);
    const { weekly: _weekly, ...rest } = item;
    return {
      ...rest,
      id: `w${weekNumber}-${template.dayType}-${item.exerciseId}-${item.order}`,
      perSide: item.perSide ?? false,
      optional: item.optional ?? false,
      recommendedWeight: item.recommendedWeight ?? null,
      substitutionIds: substitutionsFor(item.exerciseId),
      // This block prescribes reps and holds, never a target RIR or a load step.
      targetRirLow: null,
      targetRirHigh: null,
      weightIncrement: null,
      rampSets: 0,
    } satisfies ExercisePrescription;
  });

  return {
    id: `w${weekNumber}-${template.dayType}`,
    weekNumber,
    weekday: template.weekday,
    dayType: template.dayType,
    title: template.title,
    focus: template.focus,
    // Computed, never hand-written — a stale constant hid a real overrun.
    estimatedMinutes: estimateSessionMinutes(prescriptions),
    prescriptions,
  };
}

export function buildWeeks(): WeekPlan[] {
  return WEEK_META.map((meta, index) => {
    const weekNumber = index + 1;
    return {
      weekNumber,
      title: meta.title,
      focus: meta.focus,
      guidance: meta.guidance,
      phase: 'base',
      blockWeek: null,
      pushUpGoalLow: meta.pushUpGoalLow,
      pushUpGoalHigh: meta.pushUpGoalHigh,
      days: DAY_TEMPLATES.map((t) => buildWorkoutDay(t, weekNumber)),
    };
  });
}

