type TemplateItem = Omit<
  ExercisePrescription,
  | 'id'
  | 'substitutionIds'
  | 'perSide'
  | 'optional'
  | 'recommendedWeight'
  | 'targetRirLow'
  | 'targetRirHigh'
  | 'weightIncrement'
  | 'rampSets'
> & {
  perSide?: boolean;
  optional?: boolean;
  recommendedWeight?: number | null;
  /** Per-week overrides, index 0 = week 1. */
  weekly?: Partial<
    Record<
      'repsLow' | 'repsHigh' | 'durationSecondsLow' | 'durationSecondsHigh' | 'minutes' | 'sets',
      [number, number, number, number]
    >
  >;
};

interface DayTemplate {
  weekday: Weekday;
  dayType: DayType;
  title: string;
  focus: string;
  items: TemplateItem[];
}

